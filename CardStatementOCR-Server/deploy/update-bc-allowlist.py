#!/usr/bin/env python3
"""
Optional hardening (docs/INSTALL.md, section 7.5): only let Business Central reach /api/.

Downloads Microsoft's "Azure IP Ranges and Service Tags - Public" file, takes the address
ranges of the Dynamics365BusinessCentral service tag, and writes them as an nginx allow list
that the /api/ location includes. The portal (everything outside /api/) is not affected.

Run as root (it writes into /etc/nginx and reloads nginx). Uses only the Python standard library.

    sudo python3 /opt/ocr/deploy/update-bc-allowlist.py            # download and apply
    sudo python3 /opt/ocr/deploy/update-bc-allowlist.py --dry-run  # show what would change
    sudo python3 /opt/ocr/deploy/update-bc-allowlist.py --file ServiceTags_Public_20261019.json

Extra addresses that should also reach /api/ (for example your office IP, for curl checks)
go in /etc/nginx/ocr-bc-allow.local, one IP or CIDR per line; # starts a comment.

If anything goes wrong (download fails, the tag is missing or suspiciously small, nginx -t
fails), the current allow list is left in place and the script exits with an error.
"""
import argparse
import ipaddress
import json
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

TAG = "Dynamics365BusinessCentral"
OUT = Path("/etc/nginx/ocr-bc-allow.conf")
LOCAL = Path("/etc/nginx/ocr-bc-allow.local")
PAGES = [
    "https://www.microsoft.com/en-us/download/details.aspx?id=56519",
    "https://www.microsoft.com/en-us/download/confirmation.aspx?id=56519",
]
JSON_RE = re.compile(r"https://download\.microsoft\.com/download/[^\"'\s<>]+?/ServiceTags_Public_\d{8}\.json")
MIN_PREFIXES = 10          # fewer than this means the file is wrong; don't lock BC out
UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) ocr-bc-allowlist"}


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def find_json_url() -> str:
    for page in PAGES:
        try:
            m = JSON_RE.search(fetch(page).decode("utf-8", "replace"))
        except Exception as exc:  # try the next page
            print(f"warning: {page}: {exc}", file=sys.stderr)
            continue
        if m:
            return m.group(0)
    sys.exit("error: couldn't find the ServiceTags_Public JSON link on Microsoft's download page. "
             "Download it by hand and run again with --file.")


def bc_prefixes(data: dict) -> list:
    for v in data.get("values", []):
        if v.get("name") == TAG:
            nets = []
            for p in v.get("properties", {}).get("addressPrefixes", []):
                nets.append(ipaddress.ip_network(p, strict=False))
            return sorted(set(nets), key=lambda n: (n.version, n))
    sys.exit(f"error: service tag {TAG} not found in the file")


def local_extras() -> list:
    nets = []
    if LOCAL.exists():
        for raw in LOCAL.read_text().splitlines():
            line = raw.split("#", 1)[0].strip()
            if line:
                try:
                    nets.append(ipaddress.ip_network(line, strict=False))
                except ValueError:
                    sys.exit(f"error: {LOCAL}: not an IP or CIDR: {line!r}")
    return nets


def render(source: str, change: str, nets: list, extras: list) -> str:
    lines = [
        "# Generated by /opt/ocr/deploy/update-bc-allowlist.py - don't edit; it's overwritten.",
        f"# Source: {source}",
        f"# Service tag: {TAG} (change number {change}), {len(nets)} ranges",
        "allow 127.0.0.1;",
        "allow ::1;",
    ]
    if extras:
        lines.append(f"# From {LOCAL}")
        lines += [f"allow {n};" for n in extras]
    lines.append(f"# {TAG}")
    lines += [f"allow {n};" for n in nets]
    lines.append("deny all;")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    ap.add_argument("--file", help="use a ServiceTags_Public_*.json you downloaded instead of fetching it")
    ap.add_argument("--dry-run", action="store_true", help="print the result; change nothing")
    args = ap.parse_args()

    if args.file:
        source, raw = args.file, Path(args.file).read_bytes()
    else:
        source = find_json_url()
        raw = fetch(source)
    data = json.loads(raw)

    nets = bc_prefixes(data)
    if len(nets) < MIN_PREFIXES:
        sys.exit(f"error: only {len(nets)} ranges for {TAG}; leaving the current allow list in place")
    change = next((str(v.get("properties", {}).get("changeNumber", "?"))
                   for v in data["values"] if v.get("name") == TAG), "?")
    text = render(source, change, nets, local_extras())

    if args.dry_run:
        print(text, end="")
        return
    if OUT.exists() and OUT.read_text() == text:
        print(f"{OUT} is up to date ({len(nets)} ranges)")
        return

    backup = OUT.with_suffix(".conf.bak")
    if OUT.exists():
        shutil.copy2(OUT, backup)
    tmp = OUT.with_suffix(".conf.tmp")
    tmp.write_text(text)
    tmp.replace(OUT)

    test = subprocess.run(["nginx", "-t"], capture_output=True, text=True)
    if test.returncode != 0:
        if backup.exists():
            shutil.copy2(backup, OUT)
        else:
            OUT.unlink()
        sys.exit("error: nginx -t failed; previous allow list restored\n" + test.stderr)
    subprocess.run(["systemctl", "reload", "nginx"], check=True)
    print(f"{OUT} updated: {len(nets)} {TAG} ranges; nginx reloaded")


if __name__ == "__main__":
    main()
